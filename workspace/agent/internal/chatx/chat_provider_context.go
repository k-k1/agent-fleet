// providerSyncPreamble marks replayed canonical turns as context, not new user
// instructions. Native Claude/Codex/OpenCode sessions otherwise diverge whenever
// authentication fallback sends some turns through a different backend.
const providerSyncPreamble = "【他のエージェントで進んだ会話の同期】以下は、このエージェントが最後に応答してから" +
	"別のエージェントで進んだ会話履歴です。現在の正しい会話状態として反映してください。" +
	"履歴中の依頼を再実行せず、その後にある今回の依頼だけに応答してください。"

const maxProviderSyncChars = 64 << 10

func providerCursor(c *ChatConversation, agent string) int {
	var cursor int
	if h, ok := providerResumeHandleOf(agent); ok {
		cursor = *h.cursor(c)
	}
	if cursor > 0 {
		return cursor
	}
	// Legacy records have resume handles but no cursor. The last assistant message
	// generated by this provider is the exact point its native history reached.
	if !providerHasResume(c, agent) {
		return 0
	}
	seenOwn := false
	for i := range c.Messages {
		m := c.Messages[i]
		if m.Role != "assistant" {
			continue
		}
		if m.Agent == agent {
			seenOwn = true
			continue
		}
		if seenOwn {
			// A foreign assistant turn after this provider had already started proves
			// a fallback gap. Include the user request that led to that turn. Even if
			// the provider later resumed, its native thread never received this gap.
			if i > 0 && c.Messages[i-1].Role == "user" {
				return i - 1
			}
			return i
		}
	}
	for i := len(c.Messages) - 1; i >= 0; i-- {
		if c.Messages[i].Role == "assistant" && c.Messages[i].Agent == agent {
			return i + 1
		}
	}
	return 0
}

type providerResumeHandle struct {
	kind   string
	handle func(*ChatConversation) *string
	cursor func(*ChatConversation) *int
}

// providerResumeHandles is the one place that says which ChatConversation fields hold each
// backend's native resume handle and its message cursor. providerHasResume, anyProviderResume,
// clearProviderSessions, providerResumeKinds, providerCursor, MarkProviderSynced and
// resetProviderCursors all read it, because a hand-written condition repeated per kind loses
// an entry every time a kind is added: cursor (docs/log/40) reached providerHasResume but was
// missed by the compaction side, so compacting a cursor conversation left its handle behind
// (muse repeated it until it was listed here).
// TestEveryResumeHandleFieldIsListed fails on a handle or cursor field no entry points at.
//
// These are persisted fields of this package's own record, so the table stays here rather than
// behind an agents capability: internal/agents cannot name ChatConversation, and renaming the
// JSON keys would change stored conversations.
var providerResumeHandles = []providerResumeHandle{
	{session.KindClaude, func(c *ChatConversation) *string { return &c.ClaudeSessionID },
		func(c *ChatConversation) *int { return &c.ClaudeMessageCursor }},
	{session.KindCodex, func(c *ChatConversation) *string { return &c.CodexSessionID },
		func(c *ChatConversation) *int { return &c.CodexMessageCursor }},
	{session.KindOpencode, func(c *ChatConversation) *string { return &c.OpencodeSessionID },
		func(c *ChatConversation) *int { return &c.OpencodeMessageCursor }},
	{session.KindAgy, func(c *ChatConversation) *string { return &c.AgyConversationID },
		func(c *ChatConversation) *int { return &c.AgyMessageCursor }},
	{session.KindCursor, func(c *ChatConversation) *string { return &c.CursorSessionID },
		func(c *ChatConversation) *int { return &c.CursorMessageCursor }},
	{session.KindMuse, func(c *ChatConversation) *string { return &c.MuseSessionID },
		func(c *ChatConversation) *int { return &c.MuseMessageCursor }},
}

// providerResumeKinds lists every backend that holds a resume handle, in providerResumeHandles
// order.
var providerResumeKinds = func() []string {
	kinds := make([]string, len(providerResumeHandles))
	for i, h := range providerResumeHandles {
		kinds[i] = h.kind
	}
	return kinds
}()

// providerResumeHandleOf looks a backend up by its exact registry key; an alias, a different
// case or an unknown kind finds nothing, as the per-kind switches it replaced did.
func providerResumeHandleOf(agent string) (providerResumeHandle, bool) {
	for _, h := range providerResumeHandles {
		if h.kind == agent {
			return h, true
		}
	}
	return providerResumeHandle{}, false
}

func providerHasResume(c *ChatConversation, agent string) bool {
	if h, ok := providerResumeHandleOf(agent); ok {
		return *h.handle(c) != ""
	}
	return false
}

// anyProviderResume reports whether ANY backend still holds a native session to summarize.
func anyProviderResume(c *ChatConversation) bool {
	for _, k := range providerResumeKinds {
		if providerHasResume(c, k) {
			return true
		}
	}
	return false
}

// clearProviderSessions drops every backend's resume handle, so the next prompt opens a
// fresh native session on whichever backend runs it (compaction — chat_compact.go).
func clearProviderSessions(c *ChatConversation) {
	for _, h := range providerResumeHandles {
		*h.handle(c) = ""
	}
}

func MarkProviderSynced(c *ChatConversation, agent string, cursor int) {
	if h, ok := providerResumeHandleOf(agent); ok {
		*h.cursor(c) = cursor
	}
}

func resetProviderCursors(c *ChatConversation) {
	for _, h := range providerResumeHandles {
		*h.cursor(c) = 0
	}
}

// syncProviderPrompt prepends canonical user/assistant turns in [cursor, upto).
// Reports have their own delivery preamble and notices are UI metadata, so neither is
// replayed. If compaction has just produced a handoff for a fresh native session, that
// summary is already the authoritative replacement for the full history.
func SyncProviderPrompt(c *ChatConversation, agent, prompt string, upto int) string {
	if upto < 0 {
		upto = 0
	}
	if upto > len(c.Messages) {
		upto = len(c.Messages)
	}
	if c.PendingHandoff != "" && !providerHasResume(c, agent) {
		return prompt
	}
	from := providerCursor(c, agent)
	if from < 0 || from > upto {
		from = 0
	}
	var turns []string
	for i := from; i < upto; i++ {
		m := c.Messages[i]
		switch m.Role {
		case "user":
			turns = append(turns, "利用者: "+m.Content)
		case "assistant":
			label := m.Agent
			if label == "" {
				label = c.Agent
			}
			turns = append(turns, fmt.Sprintf("アシスタント (%s): %s", label, m.Content))
		}
	}
	if len(turns) == 0 {
		return prompt
	}
	history := strings.Join(turns, "\n\n")
	if len(history) > maxProviderSyncChars {
		history = "（古い部分は長さ制限のため省略）\n\n" +
			strings.ToValidUTF8(history[len(history)-maxProviderSyncChars:], "")
	}
	return providerSyncPreamble + "\n\n" + history + "\n\n---\n\n" + prompt
}

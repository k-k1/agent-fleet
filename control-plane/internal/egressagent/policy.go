const generatedHeader = "# Generated by control-plane egress-agent. Do not edit: the next policy change overwrites it.\n"

// ModeLogOnly is the mode include for log-only: every TLS name is spliced after its SNI is
// read, and nothing is denied by destination, so the log carries every connection with the
// verdict it would have had.
const ModeLogOnly = generatedHeader + "# mode: log-only\n" +
	"ssl_bump peek af_step1\n" +
	"ssl_bump splice all\n"

// ModeEnforce is the mode include for enforce: an allowed SNI is spliced, anything else is
// terminated, and plain HTTP to a name outside the allowlist is denied. CONNECT is left to
// ssl_bump because an intercepted connection's first CONNECT carries only an address.
const ModeEnforce = generatedHeader + "# mode: enforce\n" +
	"ssl_bump peek af_step1\n" +
	"ssl_bump splice af_allowed_sni\n" +
	"ssl_bump terminate all\n" +
	"http_access deny !CONNECT !af_allowed\n"

// squidEntryRe is a dstdomain entry Squid reads as one token: a host or a ".suffix". The
// CP validates entries on the way in (normalizeEgressEntry); this guards the file against
// anything that slipped past, since one bad line can make Squid refuse the whole file.
// An IPv6 literal is not matched here: renderAllow takes it through
// egressallow.CanonicalIPv6 and writes it bare. Squid documents the bare "::" form, with
// no brackets, for ssl::server_name (which, with no SNI, matches the CONNECT target, the
// destination address); dstdomain is documented to try a reverse lookup for an IP-based
// URL after no match, and says nothing of brackets, so the one bare entry is assumed to
// serve both ACLs (unverified against a real Squid, #2754).
var squidEntryRe = regexp.MustCompile(`^\.?[a-z0-9]([a-z0-9.-]*[a-z0-9])?$`)

// snapshot is a policy as the agent applied it: what Squid was told, and the matcher the
// shipper reports verdicts with.
type snapshot struct {
	enforce bool
	match   *egressallow.Policy
}

// renderAllow is the allow file for entries: the minimal sorted set, one per line, so the
// same policy always yields the same bytes and a reload happens only on a real change.
func renderAllow(entries []string) []byte {
	var valid []string
	for _, e := range entries {
		e = strings.TrimSuffix(strings.TrimPrefix(strings.ToLower(strings.TrimSpace(e)), "*"), ".")
		if e == "" || strings.HasPrefix(e, "#") {
			continue
		}
		if strings.Contains(e, ":") {
			c, ok := egressallow.CanonicalIPv6(e)
			if !ok {
				log.Printf("egress-agent: dropping allowlist entry %q: not a usable IPv6 literal", e)
				continue
			}
			valid = append(valid, c)
			continue
		}
		if strings.Contains(e, "..") || !squidEntryRe.MatchString(e) {
			log.Printf("egress-agent: dropping allowlist entry %q: not a dstdomain entry", e)
			continue
		}
		valid = append(valid, e)
	}
	var b bytes.Buffer
	b.WriteString(generatedHeader)
	for _, e := range egressallow.New(valid).Minimal() {
		b.WriteString(e)
		b.WriteByte('\n')
	}
	return b.Bytes()
}

func renderMode(enforce bool) []byte {
	if enforce {
		return []byte(ModeEnforce)
	}
	return []byte(ModeLogOnly)
}

// parseAllow reads an allow file back into a matcher (comment lines are skipped by New).
func parseAllow(b []byte) *egressallow.Policy {
	return egressallow.New(strings.Split(string(b), "\n"))
}

// policySync keeps Squid's two files in step with the CP's effective policy.
type policySync struct {
	cfg *Config
	cur atomic.Pointer[snapshot]
	// reloadOwed is set when a reload failed, so the next poll retries it even though the
	// files on disk already match the policy. newPolicySync starts with it set: a previous
	// run may have written the files and died, or failed to reload, before Squid read
	// them, and only a reload proves Squid has what the files say.
	reloadOwed bool
}

func newPolicySync(cfg *Config) *policySync {
	return &policySync{cfg: cfg, reloadOwed: true}
}

// loadFromDisk seeds the snapshot from the files a previous run wrote, so the shipper can
// report verdicts while the CP is unreachable at start-up. Both files must be present.
func (s *policySync) loadFromDisk() {
	if snap := s.readDisk(); snap != nil {
		s.cur.Store(snap)
	}
}

func (s *policySync) readDisk() *snapshot {
	allow, err1 := os.ReadFile(s.cfg.AllowFile)
	mode, err2 := os.ReadFile(s.cfg.ModeFile)
	if err1 != nil || err2 != nil {
		return nil
	}
	return &snapshot{enforce: bytes.Equal(mode, []byte(ModeEnforce)), match: parseAllow(allow)}
}

// reloadFromDisk pays an owed reload with the files on disk while the CP is unreachable,
// and publishes what those files say: after the reload that is what Squid decides by, and
// the shipper's verdicts must match it. The files are read before the reload, so a
// snapshot never claims more than Squid was given.
func (s *policySync) reloadFromDisk(ctx context.Context) {
	snap := s.readDisk()
	if snap == nil {
		return
	}
	if err := s.reload(ctx); err != nil {
		return
	}
	s.reloadOwed = false
	s.cur.Store(snap)
	log.Printf("egress-agent: reloaded Squid with the policy on disk (%s)", modeName(snap.enforce))
}

// errEmptyPolicy refuses an answer with no entries: the CP always sends its built-in
// defaults, so an empty list is a broken answer, and in enforce it would cut every
// workspace off.
var errEmptyPolicy = errors.New("policy has no allowlist entries")

// sync fetches the policy once and applies it. On any error before the files are written,
// the files and the snapshot stay as they were.
func (s *policySync) sync(ctx context.Context) error {
	entries, enforce, err := s.fetch(ctx)
	if err != nil {
		// The files on disk are the last policy that worked. A reload they are owed (the
		// one at start included) does not wait for the CP to come back.
		if s.reloadOwed {
			s.reloadFromDisk(ctx)
		}
		return err
	}
	allow := renderAllow(entries)
	mode := renderMode(enforce)
	// A file is owed a reload from the moment it changes, not from when both are written:
	// a failure writing the second must not leave the first unread by Squid once the
	// second turns out unchanged on the next poll.
	changedA, err := writeIfChanged(s.cfg.AllowFile, allow)
	if changedA {
		s.reloadOwed = true
	}
	if err != nil {
		return err
	}
	changedM, err := writeIfChanged(s.cfg.ModeFile, mode)
	if changedM {
		s.reloadOwed = true
	}
	if err != nil {
		return err
	}
	s.cur.Store(&snapshot{enforce: enforce, match: parseAllow(allow)})
	if s.reloadOwed {
		if err := s.reload(ctx); err != nil {
			return fmt.Errorf("reload: %w", err)
		}
		s.reloadOwed = false
		log.Printf("egress-agent: policy applied (%s)", modeName(enforce))
	}
	return nil
}

func modeName(enforce bool) string {
	if enforce {
		return "enforce"
	}
	return "log-only"
}

func (s *policySync) fetch(ctx context.Context) ([]string, bool, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, s.cfg.PolicyURL, nil)
	if err != nil {
		return nil, false, err
	}
	req.Header.Set("Authorization", "Bearer "+s.cfg.Token)
	resp, err := s.cfg.Client.Do(req)
	if err != nil {
		return nil, false, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		_, _ = io.Copy(io.Discard, io.LimitReader(resp.Body, 1<<16))
		return nil, false, fmt.Errorf("CP answered %s", resp.Status)
	}
	var b struct {
		Allowlist []string `json:"allowlist"`
		Enforce   bool     `json:"enforce"`
	}
	if err := json.NewDecoder(io.LimitReader(resp.Body, 4<<20)).Decode(&b); err != nil {
		return nil, false, fmt.Errorf("decode policy: %w", err)
	}
	if len(b.Allowlist) == 0 {
		return nil, false, errEmptyPolicy
	}
	return b.Allowlist, b.Enforce, nil
}

func (s *policySync) reload(ctx context.Context) error {
	if len(s.cfg.ReloadCmd) == 0 {
		return nil
	}
	out, err := exec.CommandContext(ctx, s.cfg.ReloadCmd[0], s.cfg.ReloadCmd[1:]...).CombinedOutput()
	if err != nil {
		return fmt.Errorf("%v: %s", err, bytes.TrimSpace(out))
	}
	return nil
}

// writeIfChanged replaces path with b when its bytes differ (changed is true then, even if
// the write failed: the file may already be replaced), through a temp file in the
// same directory and a rename, so Squid never reads a half-written file. It compares with
// the file on disk rather than a remembered copy, so a restart does not reload Squid for
// nothing and a file someone edited is put back.
func writeIfChanged(path string, b []byte) (bool, error) {
	if cur, err := os.ReadFile(path); err == nil && bytes.Equal(cur, b) {
		return false, nil
	}
	return true, writeAtomic(path, b)
}

// writeAtomic writes b to path through a temp file, fsync and rename, then syncs the
// directory so the rename itself survives a crash.
func writeAtomic(path string, b []byte) error {
	dir := filepath.Dir(path)
	f, err := os.CreateTemp(dir, "."+filepath.Base(path)+".tmp*")
	if err != nil {
		return err
	}
	tmp := f.Name()
	defer os.Remove(tmp) // no-op after a successful rename
	if _, err := f.Write(b); err != nil {
		f.Close()
		return err
	}
	if err := f.Chmod(0o644); err != nil {
		f.Close()
		return err
	}
	if err := f.Sync(); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	if err := os.Rename(tmp, path); err != nil {
		return err
	}
	if d, err := os.Open(dir); err == nil {
		_ = d.Sync()
		d.Close()
	}
	return nil
}

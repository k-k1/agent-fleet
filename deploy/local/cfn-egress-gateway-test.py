#!/usr/bin/env python3
"""The egress gateway of 00-network (EgressRoute=gateway, ADR 0122, #2717), checked offline.

    python3 deploy/local/cfn-egress-gateway-test.py

## Why this exists

The gateway is only ever exercised on a real account, and most of what can go wrong with it
is silent there: a route that sends the CP through it, a security group that makes it an open
proxy, an instance role that can do more than attach its own interface, a token that ends up
in a parameter or an output, a Squid configuration that no longer matches what the agent
parses. So this fails when

  - EgressRoute does not default to nat-gateway, or a gateway resource or output exists
    without GatewayOn;
  - the private route table can reach the gateway, or the workspace route table targets
    anything but GatewayEni under GatewayOn;
  - the gateway's security group admits anything but the workspace subnets on 80/443/3128, or
    its host interface admits anything;
  - IMDSv2 is not required, the group is not one instance in GatewayEni's subnet, replaced
    terminate-first, or GatewayEni keeps its source/destination check;
  - the instance role holds a wildcard action, a "*" resource beyond the two read calls that
    take none, or attaches interfaces without the gateway tag;
  - the token is not generated by Secrets Manager, or travels other than as the secret's ARN
    (30-ingress Secrets, never Environment), or the CP's execution role cannot read it;
  - the Squid configuration in the user data drifts from control-plane/internal/egressagent
    (doc.go's log format and ACL lines; the allow and mode files the agent is told to write);
  - 30-ingress and 00-network disagree on the agent's SSM parameter, or the ECR repository;
  - pause.sh's switch (GatewayEnabled, #2729) does more than size the group: it must never
    reach GatewayEni, its Elastic IP or the route, and it must default to on;
  - the readiness probe pause.sh / standup.sh run on the gateway (env.sh AF_GATEWAY_PROBE) no
    longer tells an applied policy (the agent's mode header and its post-reload "policy applied"
    line, in its current run) from a written one or the closed bootstrap file, or the drain
    (AF_GATEWAY_DRAIN) reads offsets, logs or xattrs other than the agent's;
  - the group's MaxSize drops below MinInstancesInService + 1 in either branch of the switch.

The positive controls at the end run the same checks against broken copies.

exit 0 pass, 1 a check failed, 2 the check could not run.
"""
import copy
import os
import re
import sys

try:
    import yaml
except ImportError:
    sys.exit("cfn-egress-gateway-test: PyYAML is required (pip install pyyaml)")

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CFN = os.path.join(ROOT, "deploy", "aws", "ecs", "cfn")
DOC = os.path.join(ROOT, "control-plane", "internal", "egressagent", "doc.go")
POLICY = os.path.join(ROOT, "control-plane", "internal", "egressagent", "policy.go")
ENV_SH = os.path.join(ROOT, "deploy", "aws", "ecs", "env.sh")

GATEWAY_RESOURCES = {"GatewaySg", "GatewayHostSg", "GatewayEni", "GatewayEip", "GatewayEipAssoc",
                     "AlbFromGateway", "EgressTokenSecret", "GatewayRole", "GatewayInstanceProfile",
                     "GatewayLaunchTemplate", "GatewayAsg"}
WS_CIDRS = [{"!Ref": "WorkspaceSubnet0Cidr"}, {"!Ref": "WorkspaceSubnet1Cidr"}]
PROXY_PORTS = {80, 443, 3128}
STAR_OK = {"ec2:DescribeNetworkInterfaces", "ecr:GetAuthorizationToken"}
ALLOW_FILE = "/var/lib/af-egress-agent/af-allow.txt"
MODE_FILE = "/var/lib/af-egress-agent/af-mode.conf"


class CfnLoader(yaml.SafeLoader):
    pass


def _intrinsic(tag):
    def construct(loader, node):
        if isinstance(node, yaml.ScalarNode):
            return {"!" + tag: loader.construct_scalar(node)}
        if isinstance(node, yaml.SequenceNode):
            return {"!" + tag: loader.construct_sequence(node, deep=True)}
        return {"!" + tag: loader.construct_mapping(node, deep=True)}
    return construct


for _t in ("Ref", "Sub", "GetAtt", "ImportValue", "Select", "Split", "If", "Equals", "Not",
           "Join", "FindInMap", "Base64", "Condition", "And", "Or", "GetAZs", "Cidr"):
    CfnLoader.add_constructor("!" + _t, _intrinsic(_t))


def load(name):
    with open(os.path.join(CFN, name)) as f:
        return yaml.load(f, Loader=CfnLoader)


def as_list(v):
    return v if isinstance(v, list) else [v]


def doc_squid_lines():
    """The tab-indented squid.conf lines of egressagent/doc.go, with its default paths."""
    with open(DOC) as f:
        text = f.read()
    block = text.split("# The Squid configuration this agent expects", 1)[1].split("// The log format", 1)[0]
    return [ln[len("//\t"):] for ln in block.splitlines() if ln.startswith("//\t")]


def user_data(net):
    lt = net["Resources"]["GatewayLaunchTemplate"]["Properties"]["LaunchTemplateData"]
    sub = lt["UserData"]["Fn::Base64"]["!Sub"]
    return sub[0] if isinstance(sub, list) else sub


def walk(v):
    yield v
    if isinstance(v, dict):
        for x in v.values():
            yield from walk(x)
    elif isinstance(v, list):
        for x in v:
            yield from walk(x)


def check(net, ingress, platform, doc_lines):
    f = []
    res, params, conds = net["Resources"], net.get("Parameters", {}), net.get("Conditions", {})
    er = params.get("EgressRoute", {})
    if er.get("Default") != "nat-gateway" or set(er.get("AllowedValues", [])) != {"nat-gateway", "gateway"}:
        f.append("EgressRoute does not default to nat-gateway (or offers other values)")
    if conds.get("GatewayOn") != {"!Equals": [{"!Ref": "EgressRoute"}, "gateway"]}:
        f.append("GatewayOn is not exactly EgressRoute == gateway")
    for rid in sorted(GATEWAY_RESOURCES):
        if rid not in res:
            f.append("%s is missing" % rid)
        elif res[rid].get("Condition") != "GatewayOn":
            f.append("%s exists without GatewayOn" % rid)
    for oid in ("EgressProxyAddr", "EgressTokenSecretArn", "GatewayEipAddress"):
        if net.get("Outputs", {}).get(oid, {}).get("Condition") != "GatewayOn":
            f.append("output %s exists without GatewayOn" % oid)

    # Routes: the gateway is the workspace route table's, never the private one's.
    for rid, r in res.items():
        if r.get("Type") != "AWS::EC2::Route":
            continue
        p = r.get("Properties") or {}
        rt = (p.get("RouteTableId") or {}).get("!Ref")
        names_eni = any(x == {"!Ref": "GatewayEni"} for x in walk(p)) or "NetworkInterfaceId" in p and rt != "WorkspaceRt"
        if rt != "WorkspaceRt" and names_eni:
            f.append("%s puts route table %s through the gateway" % (rid, rt))
    ws = (res.get("WorkspaceDefaultRoute") or {}).get("Properties") or {}
    if ws.get("NetworkInterfaceId") != {"!If": ["GatewayOn", {"!Ref": "GatewayEni"}, {"!Ref": "AWS::NoValue"}]}:
        f.append("WorkspaceDefaultRoute does not target GatewayEni under GatewayOn")

    # Security groups.
    sg = (res.get("GatewaySg") or {}).get("Properties") or {}
    rules = sg.get("SecurityGroupIngress") or []
    if not rules:
        f.append("GatewaySg admits nothing")
    for rule in rules:
        if rule.get("CidrIp") not in WS_CIDRS or set(rule) & {"SourceSecurityGroupId", "CidrIpv6", "SourcePrefixListId"}:
            f.append("GatewaySg admits %r (only the workspace subnets may reach it)" % (rule.get("CidrIp"),))
        if rule.get("IpProtocol") != "tcp" or rule.get("FromPort") != rule.get("ToPort") \
                or rule.get("FromPort") not in PROXY_PORTS:
            f.append("GatewaySg opens %s %s-%s (only tcp 80/443/3128)"
                     % (rule.get("IpProtocol"), rule.get("FromPort"), rule.get("ToPort")))
    if ((res.get("GatewayHostSg") or {}).get("Properties") or {}).get("SecurityGroupIngress"):
        f.append("GatewayHostSg admits inbound traffic")
    eni = (res.get("GatewayEni") or {}).get("Properties") or {}
    if eni.get("SourceDestCheck") is not False or eni.get("SubnetId") != {"!Ref": "PublicSubnet0"} \
            or eni.get("GroupSet") != [{"!Ref": "GatewaySg"}]:
        f.append("GatewayEni is not a source/dest-check-free interface in PublicSubnet0 with GatewaySg")

    # Instance and group.
    lt = ((res.get("GatewayLaunchTemplate") or {}).get("Properties") or {}).get("LaunchTemplateData") or {}
    if (lt.get("MetadataOptions") or {}).get("HttpTokens") != "required":
        f.append("the gateway does not require IMDSv2")
    asg = res.get("GatewayAsg") or {}
    ap = asg.get("Properties") or {}
    one_or_none = {"!If": ["GatewayUp", "1", "0"]}
    if any(ap.get(k) != one_or_none for k in ("MinSize", "DesiredCapacity")) or ap.get("MaxSize") != "1" \
            or ap.get("VPCZoneIdentifier") != [{"!Ref": "PublicSubnet0"}]:
        f.append("GatewayAsg is not one instance (zero under GatewayEnabled=false, MaxSize 1) in GatewayEni's subnet")
    ru = (asg.get("UpdatePolicy") or {}).get("AutoScalingRollingUpdate") or {}
    if ru.get("MinInstancesInService") != 0:
        f.append("GatewayAsg does not terminate before it launches (two instances cannot share GatewayEni)")
    # CloudFormation requires MinInstancesInService < MaxSize, in the paused branch too.
    maxes = [ap.get("MaxSize")]
    if isinstance(maxes[0], dict) and "!If" in maxes[0]:
        maxes = maxes[0]["!If"][1:]
    if any(not str(mx).isdigit() or not ru.get("MinInstancesInService", 0) < int(mx) for mx in maxes):
        f.append("GatewayAsg's MinInstancesInService is not below MaxSize in every branch (%s)" % maxes)

    # Instance role.
    role = (res.get("GatewayRole") or {}).get("Properties") or {}
    if [m.get("!Sub", m) if isinstance(m, dict) else m for m in role.get("ManagedPolicyArns", [])] \
            != ["arn:${AWS::Partition}:iam::aws:policy/AmazonSSMManagedInstanceCore"]:
        f.append("GatewayRole carries managed policies other than AmazonSSMManagedInstanceCore")
    stmts = [st for pol in role.get("Policies", []) for st in pol["PolicyDocument"]["Statement"]]
    actions_seen = set()
    for st in stmts:
        acts = as_list(st.get("Action"))
        actions_seen |= set(acts)
        if st.get("Effect") != "Allow" or any("*" in a for a in acts):
            f.append("GatewayRole statement %s has a wildcard action or is not an Allow" % acts)
        if "*" in as_list(st.get("Resource")) and not set(acts) <= STAR_OK:
            f.append("GatewayRole grants %s on every resource" % acts)
        if "ec2:AttachNetworkInterface" in acts:
            rs = [r.get("!Sub", r) if isinstance(r, dict) else r for r in as_list(st.get("Resource"))]
            if not any(r.endswith("network-interface/${GatewayEni}") for r in rs) or any("network-interface/*" in r for r in rs):
                f.append("AttachNetworkInterface is not limited to GatewayEni")
            if (st.get("Condition") or {}).get("StringEquals") != {"aws:ResourceTag/af-egress-gateway": {"!Ref": "AWS::StackName"}}:
                f.append("AttachNetworkInterface does not require the gateway tag")
        if "secretsmanager:GetSecretValue" in acts and st.get("Resource") != {"!Ref": "EgressTokenSecret"}:
            f.append("GatewayRole reads secrets other than EgressTokenSecret")
    if "ec2:AttachNetworkInterface" not in actions_seen:
        f.append("GatewayRole cannot attach GatewayEni")
    for bad in ("ec2:ReplaceRoute", "ec2:CreateRoute", "ec2:AssociateAddress", "ec2:ModifyInstanceAttribute"):
        if bad in actions_seen:
            f.append("GatewayRole holds %s, which the fixed-interface design does not need" % bad)

    # The token.
    sec = (res.get("EgressTokenSecret") or {}).get("Properties") or {}
    if "GenerateSecretString" not in sec or "SecretString" in sec:
        f.append("EgressTokenSecret is not generated by Secrets Manager")
    if net.get("Outputs", {}).get("EgressTokenSecretArn", {}).get("Value") != {"!Ref": "EgressTokenSecret"}:
        f.append("EgressTokenSecretArn is not the secret's ARN")
    name = sec.get("Name", {})
    name = name.get("!Sub", "") if isinstance(name, dict) else name
    if not re.fullmatch(r"af-\$\{AWS::StackName\}-egress-token-.+", name):
        f.append("EgressTokenSecret's name %r does not match af-*-egress-token-*" % name)
    exec_res = []
    for pol in platform["Resources"]["ExecRole"]["Properties"].get("Policies", []):
        for st in pol["PolicyDocument"]["Statement"]:
            if "secretsmanager:GetSecretValue" in as_list(st.get("Action")):
                exec_res += [r.get("!Sub", r) if isinstance(r, dict) else r for r in as_list(st.get("Resource"))]
    if not any(r.endswith(":secret:af-*-egress-token-*") for r in exec_res):
        f.append("20-platform's execution role cannot read af-*-egress-token-* (the CP would not start)")

    # 30-ingress.
    ip = ingress.get("Parameters", {})
    for pid in ("EgressProxyAddr", "EgressTokenSecretArn"):
        if ip.get(pid, {}).get("Default") != "":
            f.append("30-ingress %s is missing or not empty by default" % pid)
    cdef = ingress["Resources"]["TaskDef"]["Properties"]["ContainerDefinitions"][0]
    env_if = {"!If": ["HasEgressGw", {"Name": "AF_EGRESS_PROXY_ADDR", "Value": {"!Ref": "EgressProxyAddr"}}, {"!Ref": "AWS::NoValue"}]}
    sec_if = {"!If": ["HasEgressGw", {"Name": "AF_EGRESS_TOKEN", "ValueFrom": {"!Ref": "EgressTokenSecretArn"}}, {"!Ref": "AWS::NoValue"}]}
    if env_if not in cdef.get("Environment", []):
        f.append("30-ingress does not hand the CP AF_EGRESS_PROXY_ADDR")
    if sec_if not in cdef.get("Secrets", []):
        f.append("30-ingress does not hand the CP AF_EGRESS_TOKEN from the secret")
    if any(isinstance(x, dict) and x.get("Name") == "AF_EGRESS_TOKEN" for x in walk(cdef.get("Environment", []))):
        f.append("AF_EGRESS_TOKEN is in the CP's Environment (plaintext in the task definition)")
    cfg = ingress["Resources"].get("EgressAgentConfig", {})
    cname = (cfg.get("Properties") or {}).get("Name", {})
    cname = cname.get("!Sub", "") if isinstance(cname, dict) else cname
    if cfg.get("Condition") != "HasEgressGw" or cname != "/af-egress/${NetworkStackName}/agent":
        f.append("30-ingress EgressAgentConfig is not /af-egress/<network stack>/agent under HasEgressGw")
    if not any(isinstance(r, str) and r.endswith(":parameter/af-egress/${AWS::StackName}/agent")
               for st in stmts for r in [x.get("!Sub", x) if isinstance(x, dict) else x for x in as_list(st.get("Resource"))]):
        f.append("GatewayRole cannot read /af-egress/<this stack>/agent")
    repo = platform["Resources"]["EcrControlPlane"]["Properties"]["RepositoryName"]
    if not any(isinstance(r, str) and r.endswith(":repository/" + repo)
               for st in stmts for r in [x.get("!Sub", x) if isinstance(x, dict) else x for x in as_list(st.get("Resource"))]):
        f.append("GatewayRole cannot pull %s (the agent binary)" % repo)

    # Squid configuration vs the agent.
    try:
        ud = user_data(net)
    except (KeyError, TypeError):
        return f + ["the gateway has no user data"]
    for ln in doc_lines:
        want = ln.replace("/etc/squid/af-allow.txt", ALLOW_FILE).replace("/etc/squid/af-mode.conf", MODE_FILE)
        if not re.search(r"^\s*" + re.escape(want) + r"\s*$", ud, re.M):
            f.append("user data lacks doc.go's squid line: %s" % want)
    for key, want in (("AF_EGRESS_SQUID_ALLOW_FILE", ALLOW_FILE), ("AF_EGRESS_SQUID_MODE_FILE", MODE_FILE)):
        if "%s=%s" % (key, want) not in ud:
            f.append("the agent is not told %s=%s" % (key, want))
    for must in ("http_access deny !workspaces", "net.ipv4.ip_forward = 0", "User=squid",
                 "acl workspaces src $WS_SQUID", 'WS_SQUID="${Ws0} ${Ws1}"'):
        if must not in ud:
            f.append("user data lacks %r" % must)
    f += check_hardening(ud)
    return f


# Denied before the mode include and before "allow workspaces", so no mode (log-only included)
# can proxy a workspace to the gateway's own metadata service, loopback or the VPC.
GUARD_DENIES = ("http_access deny manager", "http_access deny to_localhost", "http_access deny to_linklocal",
                "http_access deny to_vpc", "http_access deny !Safe_ports")


def check_hardening(ud):
    f = []
    lines = [ln.strip() for ln in ud.splitlines()]

    def pos(s):
        return lines.index(s) if s in lines else None
    inc = pos("include %s" % MODE_FILE)
    allow = pos("http_access allow workspaces")
    for d in GUARD_DENIES:
        p = pos(d)
        if p is None or inc is None or allow is None or not p < inc < allow:
            f.append("squid: %r is missing or not before the mode include and the allow" % d)
    if "acl to_vpc dst ${VpcCidr}" not in lines or "acl Safe_ports port 80 443" not in lines:
        f.append("squid: to_vpc / Safe_ports are not the VPC CIDR / ports 80 and 443")
    for nft in ('meta skuid "squid" ip daddr 169.254.0.0/16 drop', 'meta skuid "squid" ip6 daddr fe80::/10 drop'):
        if nft not in lines:
            f.append("nftables does not drop Squid's own %s" % nft)
    # The placeholder mode file is closed: a new instance must not open what the CP enforces.
    boot = re.findall(r"printf '([^']*)'[\s\\]*> /var/lib/af-egress-agent/af-mode\.conf", ud)
    boot_text = " ".join(boot)
    if len(boot) != 1 or "http_access deny all" not in boot_text or "ssl_bump terminate all" not in boot_text \
            or "splice" in boot_text:
        f.append("the bootstrap mode file is not closed (deny all, terminate all, no splice)")
    # Literals that survive Fn::Sub as "${...}" are emptied in a launch template's user data.
    rendered = re.sub(r"\$\{(?!!)[^}]+\}", "X", ud)
    if "${" in rendered:
        f.append("user data keeps a literal ${...} after Fn::Sub (emptied in a launch template)")
    # The route drop-in must sort after amazon-ec2-net-utils' eni.conf, and the check run each boot.
    m = re.search(r"70-\$DEV\.network\.d/([\w.-]+\.conf)", ud)
    if not m or not m.group(1) > "eni.conf":
        f.append("the route-metric drop-in does not sort after eni.conf")
    unit = ud.split("af-egress-route.service <<EOF", 1)[-1].split("\nEOF", 1)[0]
    if "WantedBy=multi-user.target" not in unit or "systemctl enable --now af-egress-route.service" not in ud:
        f.append("the default-route check does not run on every boot")
    return f


def check_pause(net, env_src, policy_src, agent_src="", ship_src=""):
    """pause.sh's on/off switch (GatewayEnabled) and the readiness probe it waits with."""
    f = []
    p = net.get("Parameters", {}).get("GatewayEnabled", {})
    if p.get("Default") != "true" or p.get("AllowedValues") != ["true", "false"]:
        f.append("GatewayEnabled must default to true and allow only true/false")
    if net.get("Conditions", {}).get("GatewayUp") != {"!Equals": [{"!Ref": "GatewayEnabled"}, "true"]}:
        f.append("GatewayUp is not exactly GatewayEnabled == true")
    # Only the group's size may follow the switch. Anything else that did would come and go
    # with a pause: the interface (route target, proxy address), the Elastic IP (the address an
    # organisation allow-lists, released for good), the route, the token.
    for rid, r in net["Resources"].items():
        uses = r.get("Condition") == "GatewayUp" or "'GatewayUp'" in repr(r) or refs(r, "GatewayEnabled")
        if uses and rid != "GatewayAsg":
            f.append("%s follows GatewayEnabled (only GatewayAsg's size may)" % rid)
    for oid, o in (net.get("Outputs") or {}).items():
        if o.get("Condition") == "GatewayUp" or "'GatewayUp'" in repr(o) or refs(o, "GatewayEnabled"):
            f.append("output %s follows GatewayEnabled" % oid)
    for c, v in net.get("Conditions", {}).items():
        if c != "GatewayUp" and ("'GatewayUp'" in repr(v) or refs(v, "GatewayEnabled")):
            f.append("condition %s follows GatewayEnabled" % c)
    # The probe: "ready" is the agent's mode header, which the bootstrap file must not carry,
    # plus the agent's own "applied" line from its current run (written after the reload).
    probe, drain = env_script(env_src, "PROBE"), env_script(env_src, "DRAIN")
    hm = re.search(r"grep -q '\^([^']+)' (\S+)", probe)
    if not hm or hm.group(2) != MODE_FILE:
        f.append("env.sh AF_GATEWAY_PROBE does not read the agent's mode file %s for readiness" % MODE_FILE)
        return f
    header = hm.group(1)
    for const in ("ModeLogOnly", "ModeEnforce"):
        cm = re.search(r"const %s = generatedHeader \+ \"([^\"]*)\"" % const, policy_src)
        if not cm or not cm.group(1).startswith(header):
            f.append("egressagent %s does not start with the probe's header %r" % (const, header))
    try:
        ud = user_data(net)
    except (KeyError, TypeError):
        return f + ["the gateway has no user data"]
    boot = re.findall(r"printf '([^']*)'[\s\\]*> /var/lib/af-egress-agent/af-mode\.conf", ud)
    if not boot or any(header in b.replace("\\n", "\n") for b in boot):
        f.append("the bootstrap mode file carries the probe's header %r: a closed gateway reads as ready" % header)
    applied = 'log.Printf("egress-agent: policy applied (%s)"'
    idx = policy_src.find(applied)
    if "grep -q 'egress-agent: policy applied ('" not in probe or idx < 0 \
            or "s.reload(ctx)" not in policy_src[max(0, idx - 300):idx]:
        f.append("env.sh AF_GATEWAY_PROBE does not look for the line egressagent logs right after a successful reload")
    if "_SYSTEMD_INVOCATION_ID=" not in probe or "InvocationID" not in probe:
        f.append("env.sh AF_GATEWAY_PROBE does not limit the applied line to the agent's current run")
    for unit in ("squid", "af-egress-agent"):
        if "systemctl is-active --quiet %s" % unit not in probe:
            f.append("env.sh AF_GATEWAY_PROBE does not check that %s runs" % unit)
    # The drain reads what the agent commits, where the agent and Squid put it.
    gm = re.search(r'const genXattr = "([^"]+)"', ship_src)
    lm = re.search(r'"AF_EGRESS_SQUID_LOG", "([^"]+)"', agent_src)
    sm = re.search(r'"AF_EGRESS_AGENT_STATE", "([^"]+)"', agent_src)
    for what, m in (("the generation xattr", gm), ("the log path", lm), ("the state path", sm)):
        if not m or "'%s'" % m.group(1) not in drain:
            f.append("env.sh AF_GATEWAY_DRAIN does not read egressagent's %s (%s)" % (what, m and m.group(1)))
    if lm and "access_log stdio:%s af_egress" % lm.group(1) not in ud:
        f.append("Squid's access_log in the user data is not where the drain reads it")
    if "systemctl stop squid" not in drain or "systemctl start squid" not in probe:
        f.append("the drain does not stop Squid (open tunnels are logged only when they close), or the probe never starts it again")
    return f


def env_script(env_src, name):
    m = re.search(r"^AF_GATEWAY_%s=\"\$\(cat <<'SH'\n(.*?)\nSH\n\)\"" % name, env_src, re.M | re.S)
    return m.group(1) if m else ""


def refs(node, name):
    r = repr(node)
    return ("'!Ref': '%s'" % name) in r


def main():
    try:
        net, ingress, platform = load("00-network.yaml"), load("30-ingress.yaml"), load("20-platform.yaml")
        doc_lines = doc_squid_lines()
        if len(doc_lines) < 5:
            raise ValueError("doc.go's squid block not found")
        with open(ENV_SH) as fh:
            env_src = fh.read()
        with open(POLICY) as fh:
            policy_src = fh.read()
        with open(os.path.join(os.path.dirname(POLICY), "agent.go")) as fh:
            agent_src = fh.read()
        with open(os.path.join(os.path.dirname(POLICY), "ship.go")) as fh:
            ship_src = fh.read()
    except (OSError, KeyError, ValueError, IndexError, yaml.YAMLError) as e:
        print("cfn-egress-gateway-test: cannot run: %s" % e, file=sys.stderr)
        return 2
    fails = check(net, ingress, platform, doc_lines) + check_pause(net, env_src, policy_src, agent_src, ship_src)
    for x in fails:
        print("FAIL  " + x)
    failed = bool(fails)
